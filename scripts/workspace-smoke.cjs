
const { _electron: electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname,'..');

(async () => {
  const testRoot=path.join(root,'.test-data');
  await fs.mkdir(testRoot,{recursive:true});
  const data=await fs.mkdtemp(path.join(testRoot,'workspace-features-'));
  const vault = path.join(data,'vault');
  const sub = path.join(vault,'子目录');
  await fs.mkdir(sub,{recursive:true});
  const a = path.join(vault,'A.md');
  const b = path.join(vault,'B.md');
  const c = path.join(vault,'C.md');
  const moved = path.join(sub,'C.md');
  const body = '---\ntags: [writing, notes/plan]\nstatus: 草稿\n---\n\n# A\n\n普通内容 #中文标签\n\n> [!WARNING] 提醒\n> 请检查这里。\n\n[[B#段落|跳转]] 和 [相对引用](B.md#段落)。\n\n`[[B]]`\n';
  await fs.writeFile(a,body);
  await fs.writeFile(b,'# B\n\n## 段落\n\n这里是目标段落。\n\n[返回](A.md)\n');
  await fs.writeFile(path.join(data,'workspace.json'),JSON.stringify({root:vault,openFiles:[]}));
  const env={...process.env,CALCITE_TEST:'1',CALCITE_DATA_DIR:data};delete env.ELECTRON_RUN_AS_NODE;
  const app=await electron.launch({args:[root],env});
  const page=await app.firstWindow();
  page.setDefaultTimeout(12000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const file = name => page.locator('#side-content [data-file]').filter({hasText:name});
  const command = async name => {
    await page.locator('[data-action="more"]').click();
    const submenu=['html','png'].includes(name)?'export':['typewriter','paragraph'].includes(name)?'focus':null;
    if(submenu)await page.locator('#more-menu [data-submenu="'+submenu+'"]').click();
    await page.locator((submenu?'#floating-submenu':'#more-menu')+' [data-menu-command="'+name+'"]').click();
  };
  async function rename(name,next) {
    await file(name).click({button:'right'});
    await page.locator('#file-menu').getByRole('menuitem',{name:'重命名'}).click();
    await page.locator('dialog[open] input[name=name]').fill(next);
    await page.locator('dialog[open]').getByRole('button',{name:'确定'}).click();
  }
  try {
    const newFolder = page.getByRole('button',{name:'新建文件夹',exact:true});
    await newFolder.click();
    await page.locator('dialog[open] input[name=name]').fill('新建专题');
    await page.locator('dialog[open]').getByRole('button',{name:'确定'}).click();
    await page.locator('#side-content [data-folder]').getByText('新建专题',{exact:true}).waitFor();
    assert((await fs.stat(path.join(vault,'新建专题'))).isDirectory());
    await file('A.md').click();
    await page.locator('#live-properties').getByText('writing').waitFor();
    await page.locator('#live-editor [data-callout=warning]').waitFor();
    await page.locator('[data-mode=read]').click();
    await page.locator('#reading .callout-title').getByText('提醒',{exact:false}).waitFor();
    await page.locator('[data-pane=tags]').click();
    await page.locator('.tag-group summary').getByText('#中文标签',{exact:false}).waitFor();
    await page.locator('.tag-group[data-tag="notes"] > summary').click();
    await page.locator('.tag-group[data-tag="notes/plan"] > summary').getByText('#plan',{exact:false}).waitFor();
    await page.locator('[data-pane=files]').click();
    await page.keyboard.down('Control');
    await page.locator('#reading a.wiki-link').hover();
    await page.locator('.hover-preview').getByText('这里是目标段落。').waitFor();
    await page.keyboard.up('Control');
    await page.locator('[data-mode=live]').click();
    const liveWiki=page.locator('#live-editor .live-wiki');
    await page.keyboard.down('Control');
    await liveWiki.hover();
    await page.locator('.hover-preview').getByText('这里是目标段落。').waitFor();
    await page.keyboard.up('Control');
    await liveWiki.click({modifiers:['Control']});
    await page.locator('.tab.active').getByText('B.md',{exact:true}).waitFor();
    await file('A.md').click();
    await page.locator('#auto-save').click();
    await page.locator('[data-mode=source]').click();
    await page.locator('#source-editor .cm-content').click();
    await page.keyboard.press('Control+End');
    await page.keyboard.insertText('\n\n草稿引用 [[B]]');
    await page.locator('[data-mode=read]').click();
    await rename('B.md','C.md');
    await file('C.md').waitFor();
    let disk=await fs.readFile(a,'utf8');
    assert.match(disk,/\[\[(?:\.\/)?C#段落\|跳转\]\]/);
    assert.match(disk,/\(C\.md#段落\)/);
    assert(disk.includes('`[[B]]`'));
    await file('C.md').dragTo(page.locator('[data-folder]').filter({hasText:'子目录'}));
    await page.waitForFunction(target=>[...document.querySelectorAll('#side-content [data-file]')].some(row=>row.dataset.file===target),moved);
    assert((await fs.readFile(moved,'utf8')).includes('../A.md'));
    disk=await fs.readFile(a,'utf8');
    assert.match(disk,/\[\[(?:(?:\.\/)?子目录\/)?C#段落\|跳转\]\]/);
    assert(disk.includes('%E5%AD%90%E7%9B%AE%E5%BD%95/C.md'));
    assert(!disk.includes('草稿引用'));
    await page.locator('#reading').getByText('草稿引用',{exact:false}).waitFor();
    assert.equal(await page.locator('#reading .wiki-link').last().textContent(),'C');
    await page.keyboard.press('Control+f');
    await page.locator('#document-find [name=query]').fill('普通内容');
    await page.locator('#document-find [name=replacement]').fill('替换内容');
    await page.locator('#document-find [data-find=replace]').click();
    await page.locator('#reading').getByText('替换内容',{exact:false}).waitFor();
    assert(await page.locator('#reading').isVisible());
    await page.locator('#document-find [data-find=close]').click();
    await page.locator('[data-mode=live]').click();
    await page.keyboard.press('Control+f');
    await page.locator('#document-find [name=query]').fill('替换内容');
    await page.locator('#document-find [name=replacement]').fill('即时替换');
    await page.locator('#document-find [data-find=replace]').click();
    await page.locator('#live-editor').getByText('即时替换',{exact:false}).waitFor();
    await page.locator('#document-find [data-find=close]').click();
    await command('typewriter');
    await page.locator('.editor-section.typewriter-mode').waitFor();
    await command('paragraph');
    await page.locator('.editor-section.paragraph-focus').waitFor();
    await page.locator('[data-mode=source]').click();
    const source=page.locator('#source-editor .cm-content');
    await source.click();
    await page.keyboard.press('Control+End');
    await page.evaluate(()=>{
      const data=new DataTransfer();
      data.setData('text/html','<p>网页<strong>加粗</strong></p><ul><li>列表项</li></ul>');
      document.querySelector('#source-editor .cm-content').dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}));
    });
    await page.waitForFunction(()=>document.querySelector('#source-editor .cm-content').innerText.includes('**加粗**'));
    await page.keyboard.press('Control+End');
    await page.evaluate(()=>{
      const data=new DataTransfer();
      const png='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/lWQAAAAASUVORK5CYII=';
      data.items.add(new File([Uint8Array.from(atob(png),c=>c.charCodeAt(0))],'pixel.png',{type:'image/png'}));
      document.querySelector('#source-editor .cm-content').dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}));
    });
    await page.waitForFunction(()=>document.querySelector('#source-editor .cm-content').innerText.includes('assets/'));
    assert.equal((await fs.readdir(path.join(vault,'assets'))).length,1);
    await page.locator('.titlebar [data-action=more]').click();
    await page.locator('#more-menu [data-menu-command=save]').click();
    await page.waitForFunction(()=>document.querySelector('#save-state').textContent==='已保存到本地');
    await command('history');
    await page.locator('.history-dialog[open] .diff-added').first().waitFor();
    await page.locator('.history-dialog[open] select option').nth(1).waitFor({state:'attached'});
    await page.keyboard.press('Escape');
    const html=path.join(data,'standalone.html');
    await app.evaluate(({dialog},target)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:target});},html);
    await command('html');
    await page.waitForFunction(()=>document.querySelector('#toast').textContent==='HTML 已导出');
    assert.match(await fs.readFile(html,'utf8'),/data:image\/png;base64/);
    const png=path.join(data,'reading.png');
    await app.evaluate(({dialog},target)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:target});},png);
    await command('png');
    await page.locator('dialog[open]').getByRole('button',{name:'导出 PNG'}).click();
    await page.waitForFunction(()=>document.querySelector('#toast').textContent==='PNG 已导出');
    assert.equal((await fs.readFile(png)).subarray(1,4).toString(),'PNG');
    const card=path.join(data,'selection.png');
    await app.evaluate(({dialog},target)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:target});},card);
    await page.locator('[data-mode=read]').click();
    await page.locator('#reading p').filter({hasText:'即时替换'}).evaluate(el=>{
      const range=document.createRange();range.selectNodeContents(el);
      const selection=getSelection();selection.removeAllRanges();selection.addRange(range);
      document.dispatchEvent(new Event('selectionchange'));
    });
    await command('png');
    await page.locator('dialog[open] select[name=scope]').selectOption('selected');
    await page.locator('dialog[open]').getByRole('button',{name:'导出 PNG'}).click();
    await page.waitForFunction(()=>document.querySelector('#toast').textContent==='PNG 已导出');
    for(let retry=0;retry<100;retry++){
      if(await fs.stat(card).then(stat=>stat.size>24,()=>false))break;
      await new Promise(resolve=>setTimeout(resolve,100));
    }
    assert((await fs.readFile(card)).readUInt32BE(20)<600,'selection PNG should crop to its content');
    await page.locator('[data-mode=source]').click();
    await source.click();
    await page.keyboard.press('Control+End');
    await page.keyboard.insertText('\n\n[[新建笔记]]');
    await page.locator('[data-mode=read]').click();
    await page.locator('#reading .wiki-link').getByText('新建笔记').click();
    await file('新建笔记.md').waitFor();
    await fs.stat(path.join(vault,'新建笔记.md'));
    await file('新建笔记.md').click({button:'right'});
    await page.locator('#file-menu').getByRole('menuitem',{name:'移入系统回收站'}).click();
    await page.locator('dialog[open]').getByRole('button',{name:'移入回收站'}).click();
    await file('新建笔记.md').waitFor({state:'detached'});
    await assert.rejects(fs.stat(path.join(vault,'新建笔记.md')),{code:'ENOENT'});
    const second=path.join(data,'第二知识库');
    const unapproved=path.join(data,'未授权知识库');
    await Promise.all([fs.mkdir(second),fs.mkdir(unapproved)]);
    await fs.writeFile(path.join(second,'切换后的笔记.md'),'# 来自第二个知识库');
    await assert.rejects(page.evaluate(dir=>window.desktop['switch-vault'](dir,[]),unapproved),/文件夹选择器/);
    await app.evaluate(({dialog},dir)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[dir]});},second);
    await page.locator('.workspace-picker summary').click();
    await page.getByRole('button',{name:'打开工作区文件夹…',exact:true}).click();
    await file('切换后的笔记.md').waitFor();
    await page.locator('.workspace-picker summary').click();
    const picker=page.locator('#workspace-menu:popover-open');
    assert(await picker.evaluate(node=>node.parentElement===document.body));
    await picker.getByRole('button',{name:path.basename(vault),exact:true}).click();
    await page.locator('#workspace-name').filter({hasText:path.basename(vault)}).waitFor();
    assert.deepEqual(errors,[]);
    console.log('Workspace feature smoke passed.');
  } catch(error) {
    console.error(await page.locator('#toast').textContent(),errors);
    await page.screenshot({path:path.join(data,'failure.png')}).catch(()=>{});
    throw error;
  } finally { await app.evaluate(({app})=>app.exit()); }
})().catch(error=>{console.error(error);process.exitCode=1;});

