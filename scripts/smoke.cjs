  const fills=[];
  for (const theme of ['亮色','暗色']) {
   await appearance.click();
    await page.locator('#appearance-panel').getByRole('button',{name:theme,exact:true}).click();
   await page.keyboard.press('Escape');
   await diagram.waitFor();
   fills.push(await fill());
  }
  assert.notEqual(fills[0],fills[1],'Mermaid node colors must follow the current theme');
  assert.equal(await page.locator('#backlink-count').textContent(),'1');
  await page.locator('[data-pane="search"]').click();
  await page.locator('#workspace-search').fill('Smoke check');
  await page.locator('.search-result').waitFor();
